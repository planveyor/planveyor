def _deep_merge(base: dict[str, Any], override: dict[str, Any]) -> dict[str, Any]:
    merged = deepcopy(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = _deep_merge(merged[key], value)
        else:
            merged[key] = value
    return merged


def _validate_string_list(value: Any, *, field: str) -> None:
    if not isinstance(value, list) or not value:
        raise ValueError(f"Policy field `{field}` must be a non-empty string array")
    if any(not isinstance(item, str) or not item.strip() for item in value):
        raise ValueError(f"Policy field `{field}` must contain only non-empty strings")


def validate_policy_schema(policy: dict[str, Any], *, require_raw_keys: bool = False) -> None:
    if require_raw_keys:
        missing = [key for key in REQUIRED_POLICY_KEYS if key not in policy]
        if missing:
            raise ValueError("Policy JSON missing required key(s): " + ", ".join(missing))

    schema_version = policy.get("schema_version")
    if schema_version != POLICY_SCHEMA_VERSION:
        raise ValueError(f"Policy schema_version must be {POLICY_SCHEMA_VERSION!r}")

    verdict_defaults = policy.get("verdict_defaults")
    if not isinstance(verdict_defaults, dict):
        raise ValueError("Policy field `verdict_defaults` must be an object")
    for key, value in verdict_defaults.items():
        if value not in ALLOWED_VERDICTS:
            raise ValueError(
                f"Policy verdict_defaults.{key} must be one of: "
                + ", ".join(sorted(ALLOWED_VERDICTS))
            )

    detection = policy.get("detection")
    if not isinstance(detection, dict):
        raise ValueError("Policy field `detection` must be an object")
    for key in DETECTION_MARKER_KEYS:
        _validate_string_list(detection.get(key), field=f"detection.{key}")


def load_policy(path: Path) -> dict[str, Any]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError("Policy JSON must be an object")
    validate_policy_schema(payload, require_raw_keys=True)
    policy = _deep_merge(DEFAULT_POLICY, payload)
    validate_policy_schema(policy)
    return policy


def run_git(project_root: Path, args: list[str]) -> str:
    proc = subprocess.run(
        ["git", *args],
        cwd=project_root,
        text=True,
        capture_output=True,
    )
    if proc.returncode != 0:
        raise RuntimeError(proc.stderr.strip() or f"git {' '.join(args)} failed")
    return proc.stdout


def run_git_bytes(project_root: Path, args: list[str]) -> bytes:
    proc = subprocess.run(
        ["git", *args],
        cwd=project_root,
        capture_output=True,
    )
    if proc.returncode != 0:
        stderr = proc.stderr.decode("utf-8", errors="replace").strip()
        raise RuntimeError(stderr or f"git {' '.join(args)} failed")
    return proc.stdout


def collect_commits(range_ref: str, project_root: Path) -> list[dict[str, str]]:
    raw = run_git(
        project_root,
        ["log", "--format=%H%x1f%an%x1f%ae%x1f%s%x1f%b%x1e", range_ref],
    )
    commits: list[dict[str, str]] = []
    for chunk in raw.split("\x1e"):
        entry = chunk.strip()
        if not entry:
            continue
        parts = entry.split("\x1f")
        while len(parts) < 5:
            parts.append("")
        commits.append(
            {
                "commit": parts[0].strip(),
                "author_name": parts[1].strip(),
                "author_email": parts[2].strip(),
                "subject": parts[3].strip(),
                "body": parts[4].strip(),
            }
        )
    return commits


def collect_diff_metadata(range_ref: str, project_root: Path) -> dict[str, Any]:
    raw_files = run_git(
        project_root,
        ["diff", "--name-only", "--diff-filter=AMRTUXB", range_ref],
    )
    raw_numstat = run_git(
        project_root,
        ["diff", "--numstat", "--diff-filter=AMRTUXB", range_ref],
    )
    files = sorted({line.strip() for line in raw_files.splitlines() if line.strip()})
    lines_added = 0
    lines_removed = 0
    for raw in raw_numstat.splitlines():
        parts = raw.split("\t", 2)
        if len(parts) < 2:
            continue
        if parts[0].isdigit():
            lines_added += int(parts[0])
        if parts[1].isdigit():
            lines_removed += int(parts[1])
    return {
        "files": files,
        "changed_file_count": len(files),
        "lines_added": lines_added,
        "lines_removed": lines_removed,
    }


def max_risk(*tiers: str) -> str:
    current = "LOW"
    for tier in tiers:
        if RISK_ORDER[tier] > RISK_ORDER[current]:
            current = tier
    return current


def evaluate_detection(commits: list[dict[str, str]], policy: dict[str, Any]) -> dict[str, Any]:
    detection_cfg = policy["detection"]
    author_markers = [marker.lower() for marker in detection_cfg.get("author_markers", [])]
    text_markers = [
        marker.lower()
        for marker in detection_cfg.get("message_markers", []) + detection_cfg.get("session_markers", [])
    ]
    signals: list[dict[str, Any]] = []

    for commit in commits:
        fields: list[dict[str, Any]] = []
        for field_name in ("author_name", "author_email"):
            haystack = commit[field_name].lower()
            matched = [marker for marker in author_markers if marker in haystack]
            if matched:
                fields.append({"field": field_name, "markers": matched})
        for field_name in ("subject", "body"):
            haystack = commit[field_name].lower()
            matched = [marker for marker in text_markers if marker in haystack]
            if matched:
                fields.append({"field": field_name, "markers": matched})
        if fields:
            signals.append(
                {
                    "commit": commit["commit"],
                    "subject": commit["subject"],
                    "matched_fields": fields,
                }
            )

    if signals:
        return {
            "status": "CONFIRMED",
            "ai_assisted": True,
            "reason": "repo-backed AI markers found in commit metadata",
            "default_verdict_if_unconfirmed": policy["verdict_defaults"]["unconfirmed_detection"],
            "commit_count": len(commits),
            "signal_count": len(signals),
            "signals": signals,
        }

    return {
        "status": "UNCONFIRMED",
        "ai_assisted": None,
        "reason": "no AI markers found in commit metadata",
        "default_verdict_if_unconfirmed": policy["verdict_defaults"]["unconfirmed_detection"],
        "commit_count": len(commits),
        "signal_count": 0,
        "signals": [],
    }


def _matches_any(path: str, patterns: list[str]) -> bool:
    return any(fnmatch(path, pattern) for pattern in patterns)


def evaluate_policy(diff_metadata: dict[str, Any], policy: dict[str, Any]) -> dict[str, Any]:
    path_rules = policy["path_rules"]
    diff_limits = policy["diff_limits"]
    files: list[str] = diff_metadata["files"]
    blocked_paths = [path for path in files if _matches_any(path, path_rules.get("block", []))]
    allow_patterns: list[str] = path_rules.get("allow", [])
    outside_allowlist = [
        path
        for path in files
        if allow_patterns and not _matches_any(path, allow_patterns)
    ]
    threshold_hits: list[str] = []
    status = "PASS"
    risk_tier = "LOW"

    if blocked_paths:
        status = "BLOCK"
        risk_tier = "CRITICAL"
        threshold_hits.append("blocked path matched policy")

    if diff_metadata["changed_file_count"] >= diff_limits["max_changed_files_block"]:
        status = "BLOCK"
        risk_tier = max_risk(risk_tier, "CRITICAL")
        threshold_hits.append("changed file count crossed block threshold")
    elif diff_metadata["changed_file_count"] >= diff_limits["max_changed_files_warn"] and status != "BLOCK":
        status = "WARN"
        risk_tier = max_risk(risk_tier, "HIGH")
        threshold_hits.append("changed file count crossed warn threshold")

    if diff_metadata["lines_added"] >= diff_limits["max_lines_added_block"]:
        status = "BLOCK"
        risk_tier = max_risk(risk_tier, "CRITICAL")
        threshold_hits.append("lines added crossed block threshold")
    elif diff_metadata["lines_added"] >= diff_limits["max_lines_added_warn"] and status != "BLOCK":
        status = "WARN"
        risk_tier = max_risk(risk_tier, "MEDIUM")
        threshold_hits.append("lines added crossed warn threshold")

    if (
        outside_allowlist
        and path_rules.get("warn_outside_allowlist", False)
        and status != "BLOCK"
    ):
        status = "WARN"
        risk_tier = max_risk(risk_tier, "MEDIUM")
        threshold_hits.append("changed paths fall outside allowlist")

    return {
        "status": status,
        "risk_tier": risk_tier,
        "changed_files": files,
        "diff_stats": {
            "changed_file_count": diff_metadata["changed_file_count"],
            "lines_added": diff_metadata["lines_added"],
            "lines_removed": diff_metadata["lines_removed"],
        },
        "path_rules": {
            "blocked_paths": blocked_paths,
            "outside_allowlist": outside_allowlist,
        },
        "threshold_hits": threshold_hits,
    }


def _count_report_items(payload: Any) -> int:
    if isinstance(payload, list):
        return len(payload)
    if isinstance(payload, dict):
        for key in ("findings", "results"):
            value = payload.get(key)
            if isinstance(value, list):
                return len(value)
    return 0


def run_external_command(command: list[str], cwd: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        command,
        cwd=cwd,
        text=True,
        capture_output=True,
    )


def _scan_ref_from_range(range_ref: str) -> str:
    if "..." in range_ref:
        candidate = range_ref.rsplit("...", 1)[1].strip()
        return candidate or "HEAD"
    if ".." in range_ref:
        candidate = range_ref.rsplit("..", 1)[1].strip()
        return candidate or "HEAD"
    return range_ref.strip() or "HEAD"


def materialize_range_subset(
    project_root: Path,
    range_ref: str,
    changed_files: list[str],
    target_root: Path,
) -> dict[str, Any]:
    scan_ref = _scan_ref_from_range(range_ref)
    materialized_files: list[str] = []
    for rel_path in changed_files:
        if not rel_path:
            continue
        destination = target_root / rel_path
        destination.parent.mkdir(parents=True, exist_ok=True)
        payload = run_git_bytes(project_root, ["show", f"{scan_ref}:{rel_path}"])
        destination.write_bytes(payload)
        materialized_files.append(rel_path)
    return {
        "mode": "changed_files_subset",
        "scan_ref": scan_ref,
        "file_count": len(materialized_files),
        "files": materialized_files,
    }


def run_gitleaks(scan_root: Path, tool_path: str) -> dict[str, Any]:
    with tempfile.NamedTemporaryFile(suffix=".json", delete=False) as handle:
        report_path = Path(handle.name)
    command = [
        tool_path,
        "detect",
        "--no-banner",
        "--source",
        str(scan_root),
        "--report-format",
        "json",
        "--report-path",
        str(report_path),
    ]
    proc = run_external_command(command, scan_root)
    report: Any = []
    if report_path.exists() and report_path.stat().st_size:
        try:
            report = json.loads(report_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            report = []
    findings_count = _count_report_items(report)
    try:
        report_path.unlink(missing_ok=True)
    except OSError:
        pass

    if proc.returncode == 0:
        return {
            "status": "PASS",
            "reason": "scanner completed without findings",
            "command": command,
            "findings_count": findings_count,
            "degraded": False,
        }
    if proc.returncode == 1:
        return {
            "status": "BLOCK",
            "reason": "scanner reported findings",
            "command": command,
            "findings_count": findings_count or 1,
            "degraded": False,
        }
    return {
        "status": "WARN",
        "reason": proc.stderr.strip() or "scanner failed",
        "command": command,
        "findings_count": findings_count,
        "degraded": True,
    }


def run_semgrep(
    scan_root: Path,
    tool_path: str,
    config: str,
    *,
    project_root: Path,
) -> dict[str, Any]:
    config_path = Path(config).expanduser()
    if not config_path.is_absolute():
        config_path = (project_root / config_path).resolve()
    command = [
        tool_path,
        "scan",
        "--quiet",
        "--json",
        "--config",
        str(config_path),
        str(scan_root),
    ]
    proc = run_external_command(command, scan_root)
    payload: Any = {}
    if proc.stdout.strip():
        try:
            payload = json.loads(proc.stdout)
        except json.JSONDecodeError:
            payload = {}
    findings_count = _count_report_items(payload)
    if proc.returncode == 0:
        return {
            "status": "PASS",
            "reason": "scanner completed without findings",
            "command": command,
            "findings_count": findings_count,
            "degraded": False,
        }
    if proc.returncode == 1:
        return {
            "status": "BLOCK",
            "reason": "scanner reported findings",
            "command": command,
            "findings_count": findings_count or 1,
            "degraded": False,
        }
    return {
        "status": "WARN",
        "reason": proc.stderr.strip() or "scanner failed",
        "command": command,
        "findings_count": findings_count,
        "degraded": True,
    }


def evaluate_security_scans(
    range_ref: str,
    project_root: Path,
    diff_metadata: dict[str, Any],
    policy: dict[str, Any],
) -> dict[str, Any]:
    changed_files: list[str] = diff_metadata["files"]
    lanes: list[dict[str, Any]] = []
    overall = "PASS"
    degraded = False
    scope: dict[str, Any] = {
        "mode": "changed_files_subset",
        "scan_ref": _scan_ref_from_range(range_ref),
        "file_count": 0,
        "files": [],
    }
    scan_root: Path | None = None
    scan_tempdir: tempfile.TemporaryDirectory[str] | None = None

    try:
        for name, config in policy["security_scans"].items():
            enabled = bool(config.get("enabled", False))
            required = bool(config.get("required", False))
            if not enabled:
                lanes.append(
                    {
                        "name": name,
                        "status": "SKIPPED",
                        "reason": "disabled_by_policy",
                        "required": required,
                        "degraded": False,
                    }
                )
                continue

            if not changed_files:
                lanes.append(
                    {
                        "name": name,
                        "status": "SKIPPED",
                        "reason": "no_changed_files_in_range",
                        "required": required,
                        "degraded": False,
                    }
                )
                continue

            if scan_root is None:
                scan_tempdir = tempfile.TemporaryDirectory()
                scan_root = Path(scan_tempdir.name)
                scope = materialize_range_subset(project_root, range_ref, changed_files, scan_root)

            tool_path = shutil.which(name)
            if not tool_path:
                lane = {
                    "name": name,
                    "status": "SKIPPED",
                    "reason": "tool_not_found",
                    "required": required,
                    "degraded": True,
                }
                lanes.append(lane)
                degraded = True
                if required:
                    overall = "BLOCK"
                elif overall != "BLOCK":
                    overall = "WARN"
                continue

            if name == "gitleaks":
                result = run_gitleaks(scan_root, tool_path)
            elif name == "semgrep":
                config_path = str(config.get("config", "")).strip()
                if not config_path:
                    result = {
                        "status": "SKIPPED",
                        "reason": "missing_policy_config",
                        "command": [],
                        "findings_count": 0,
                        "degraded": False,
                    }
                else:
                    result = run_semgrep(
                        scan_root,
                        tool_path,
                        config_path,
                        project_root=project_root,
                    )
            else:
                result = {
                    "status": "SKIPPED",
                    "reason": "unsupported_scanner",
                    "command": [],
                    "findings_count": 0,
                    "degraded": False,
                }

            lane = {"name": name, "required": required, **result}
            lanes.append(lane)
            degraded = degraded or lane.get("degraded", False)
            if lane["status"] == "BLOCK" or (required and lane["status"] in {"WARN", "SKIPPED"}):
                overall = "BLOCK"
            elif lane["status"] in {"WARN", "SKIPPED"} and overall != "BLOCK":
                overall = "WARN"
    finally:
        if scan_tempdir is not None:
            scan_tempdir.cleanup()

    return {
        "status": overall,
        "degraded": degraded,
        "scope": scope,
        "lanes": lanes,
    }


def evaluate_satd(range_ref: str, project_root: Path, policy: dict[str, Any]) -> dict[str, Any]:
    candidates = satd_scan.scan_range(range_ref, project_root)
    warnable_candidates = [item for item in candidates if item.lifecycle != "deleted"]
    blocker_count = sum(1 for item in warnable_candidates if item.blocker_signal)
    deleted_count = sum(1 for item in candidates if item.lifecycle == "deleted")
    test_context_count = sum(1 for item in candidates if item.test_context)
    status = "CLEAN"
    warn_reasons: list[str] = []
    if warnable_candidates and policy["satd_candidates"].get("warn_on_any", True):
        status = "WARN"
        warn_reasons.append("SATD candidates require manual review")
    if blocker_count and policy["satd_candidates"].get("warn_on_blocker_signal", True):
        status = "WARN"
        warn_reasons.append("SATD candidate includes blocker-signal wording")
    return {
        "status": status,
        "count": len(candidates),
        "warnable_count": len(warnable_candidates),
        "deleted_count": deleted_count,
        "blocker_count": blocker_count,
        "test_context_count": test_context_count,
        "manual_review_required": bool(warnable_candidates),
        "reasons": warn_reasons,
        "candidates": [asdict(item) for item in candidates],
    }


def _max_severity(current: str, candidate: str) -> str:
    return candidate if SEVERITY_ORDER[candidate] > SEVERITY_ORDER[current] else current


def evaluate_verdict(
    detection: dict[str, Any],
    policy_lane: dict[str, Any],
    security_scans: dict[str, Any],
    satd_candidates: dict[str, Any],
    policy: dict[str, Any],
) -> dict[str, Any]:
    status = "PASS"
    reasons: list[str] = []
    risk_tier = policy_lane["risk_tier"]
    degraded = security_scans["degraded"]

    if detection["status"] == "UNCONFIRMED":
        unconfirmed_default = policy["verdict_defaults"]["unconfirmed_detection"]
        status = _max_severity(status, unconfirmed_default)
        if unconfirmed_default != "PASS":
            reasons.append(
                f"detection stayed {detection['status']}; default verdict {unconfirmed_default}"
            )
            risk_tier = max_risk(risk_tier, "MEDIUM")

    status = _max_severity(status, policy_lane["status"])
    if policy_lane["status"] != "PASS":
        reasons.extend(policy_lane["threshold_hits"] or ["policy lane raised risk"])
        risk_tier = max_risk(risk_tier, policy_lane["risk_tier"])

    for lane in security_scans["lanes"]:
        lane_status = lane["status"]
        if lane_status == "BLOCK":
            status = _max_severity(status, "BLOCK")
            reasons.append(f"{lane['name']} reported findings")
            risk_tier = max_risk(risk_tier, "CRITICAL")
        elif lane_status == "WARN":
            status = _max_severity(status, "WARN")
            reasons.append(f"{lane['name']} returned WARN: {lane['reason']}")
            risk_tier = max_risk(risk_tier, "HIGH")
        elif lane_status == "SKIPPED" and lane.get("degraded"):
            skipped_default = policy["verdict_defaults"]["missing_optional_scanner"]
            status = _max_severity(status, skipped_default)
            reasons.append(f"{lane['name']} skipped: {lane['reason']}")
            risk_tier = max_risk(risk_tier, "MEDIUM")

    if satd_candidates["status"] == "WARN":
        satd_default = policy["verdict_defaults"]["satd_candidate"]
        status = _max_severity(status, satd_default)
        reasons.extend(satd_candidates["reasons"])
        risk_tier = max_risk(risk_tier, "MEDIUM")

    if not reasons:
        reasons.append("all configured lanes stayed within policy")

    return {
        "status": status,
        "risk_tier": risk_tier,
        "degraded": degraded or detection["status"] == "UNCONFIRMED",
        "reasons": reasons,
    }


def build_receipt(range_ref: str, project_root: Path, policy: dict[str, Any]) -> dict[str, Any]:
    commits = collect_commits(range_ref, project_root)
    diff_metadata = collect_diff_metadata(range_ref, project_root)
    detection = evaluate_detection(commits, policy)
    policy_lane = evaluate_policy(diff_metadata, policy)
    security_scans = evaluate_security_scans(range_ref, project_root, diff_metadata, policy)
    satd_candidates = evaluate_satd(range_ref, project_root, policy)
    verdict = evaluate_verdict(detection, policy_lane, security_scans, satd_candidates, policy)
    return {
        "schema_version": "ai_gate_receipt.v1",
        "event_type": "review.pre_merge_ai_gate",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "project_root": str(project_root),
        "range": range_ref,
        "detection": detection,
        "policy": policy_lane,
        "security_scans": security_scans,
        "satd_candidates": satd_candidates,
        "verdict": verdict,
        "receipt_policy": {
            "schema_version": policy.get("schema_version", DEFAULT_POLICY["schema_version"]),
            "source": "policy file + defaults",
        },
    }


def default_receipt_path(project_root: Path, range_ref: str) -> Path:
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    safe_range = re.sub(r"[^A-Za-z0-9_-]+", "_", range_ref).strip("_") or "range"
    return project_root / "docs" / "reviews" / f"{stamp}_ai_gate_{safe_range}.json"


def write_receipt(receipt: dict[str, Any], target: Path) -> Path:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(receipt, ensure_ascii=False, indent=2) + os.linesep, encoding="utf-8")
    return target


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    project_root = (
        Path(args.project_root).expanduser().resolve()
        if args.project_root
        else Path.cwd().resolve()
    )
    policy_path = Path(args.policy).expanduser().resolve()

    try:
        policy = load_policy(policy_path)
        receipt = build_receipt(args.range_ref, project_root, policy)
        receipt_path = (
            Path(args.receipt_path).expanduser().resolve()
            if args.receipt_path
            else default_receipt_path(project_root, args.range_ref)
        )
        write_receipt(receipt, receipt_path)
    except (RuntimeError, ValueError, json.JSONDecodeError) as exc:
        print(str(exc), file=sys.stderr)
        return 1

    summary = {
        "receipt_path": str(receipt_path),
        "range": args.range_ref,
        "verdict": receipt["verdict"]["status"],
        "risk_tier": receipt["verdict"]["risk_tier"],
    }
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    if receipt["verdict"]["status"] == "BLOCK":
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
